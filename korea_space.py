# 숫자 변환
# =====================================================

def to_number(value):

    if value is None:

        return None


    if isinstance(
        value,
        (int, float)
    ):

        return value


    text = str(value).strip()


    if text == "":

        return None


    text = text.replace(
        ",",
        ""
    )


    try:

        number = float(text)


        if number.is_integer():

            return int(number)


        return number


    except ValueError:

        return None


