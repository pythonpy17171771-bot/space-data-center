# 분야명 정규화
# =====================================================

def normalize_field(field):

    if not field:

        return field


    field = str(field).strip()


    # ---------------------------------------------
    # 원격탐사
    # ---------------------------------------------

    if field in [

        "원격탐사",

        "위성탐사"

    ]:

        return "원격탐사"


    # ---------------------------------------------
    # 위성방송통신
    # ---------------------------------------------

    if field in [

        "위성방송통신",

        "위성통신방송"

    ]:

        return "위성방송통신"


    # ---------------------------------------------
    # 위성항법
    # ---------------------------------------------

    if field == "위성항법":

        return "위성항법"


    return field


