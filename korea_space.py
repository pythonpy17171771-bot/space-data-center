# 분야명 분석
# =====================================================

def parse_category(name):

    if not name:

        return {

            "metric":
                "분류 미상",

            "field":
                "분류 미상"

        }


    name = str(name).strip()


    # ---------------------------------------------
    # 매출액
    # ---------------------------------------------

    if name.startswith("매출액_"):

        field = name.replace(

            "매출액_",

            "",

            1

        )


        return {

            "metric":
                "매출액",

            "field":
                normalize_field(field)

        }


    # ---------------------------------------------
    # 수출액
    # ---------------------------------------------

    if name.startswith("수출액_"):

        field = name.replace(

            "수출액_",

            "",

            1

        )


        return {

            "metric":
                "수출액",

            "field":
                normalize_field(field)

        }


    # ---------------------------------------------
    # 수입액
    # ---------------------------------------------

    if name.startswith("수입액_"):

        field = name.replace(

            "수입액_",

            "",

            1

        )


        return {

            "metric":
                "수입액",

            "field":
                normalize_field(field)

        }


    return {

        "metric":
            "기타",

        "field":
            name

    }


# =====================================================
# API 데이터 정리
# =====================================================

def organize_api_data(api_data):

    records = api_data.get(

        "data",

        []

    )


    print(

        "[KOREA SPACE] API 원본 행:",

        len(records)

    )


    categories = {}


    for row in records:

        raw_category = row.get(

            "분야별"

        )


        if raw_category is None:

            continue


        raw_category = str(

            raw_category

        ).strip()


        parsed = parse_category(

            raw_category

        )


        metric = parsed["metric"]

        field = parsed["field"]


        # ---------------------------------------------
        # 최종 항목명
        # ---------------------------------------------

        if metric in [

            "매출액",

            "수출액",

            "수입액"

        ]:

            name = (

                f"{metric}_{field}"

            )

        else:

            name = raw_category


        # ---------------------------------------------
        # 새로운 항목
        # ---------------------------------------------

        if name not in categories:

            categories[name] = {

                "name":
                    name,

                "metric":
                    metric,

                "field":
                    field,

                "unit":
                    UNIT,

                "values":
                    {}

            }


        # ---------------------------------------------
        # 2010 ~ 2021
        # ---------------------------------------------

        for year in API_YEARS:

            categories[name][
                "values"
            ][year] = to_number(

                row.get(year)

            )


    return categories


